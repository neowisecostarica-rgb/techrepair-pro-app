import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const main = readFileSync('src/main.jsx', 'utf8');
const boundary = readFileSync('src/components/diagnostics/AppErrorBoundary.jsx', 'utf8');
const layout = readFileSync('src/Layout.jsx', 'utf8');
const app = readFileSync('src/App.jsx', 'utf8');
assert.ok(main.includes("import AppErrorBoundary from '@/components/diagnostics/AppErrorBoundary'"));
assert.ok(main.includes('<AppErrorBoundary><I18nProvider><App /></I18nProvider></AppErrorBoundary>'), 'render boundary wraps AuthProvider, router and whole application');
assert.ok(boundary.includes('static getDerivedStateFromError()'));
assert.ok(boundary.includes('componentDidCatch(error, info)'));
assert.ok(boundary.includes('role="alert"'));
assert.ok(boundary.includes('SEC-019 · REACT_ROOT'));
assert.ok(boundary.includes('window.location.reload()'));
assert.ok(!boundary.includes('error?.message'), 'diagnostics should not include message potentially containing personal data');
assert.ok(!boundary.includes('this.state.error'), 'do not display exceptions with sensitive details');
assert.ok(app.includes('<AuthProvider>'));
assert.ok(layout.includes('authorizedOrganizations.find(org => org?.id === effectiveOrgId)'), 'previous SEC-018 protection remains');
assert.ok(layout.includes("organization?.status === 'suspended' && !isImpersonating"), 'suspension blocking remains');
console.log('PASS SEC-019 root React render boundary, privacy-preserving console and auth barriers retained');
